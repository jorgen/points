class EmitError(Exception):
    pass


def san(name):
    return name + "_" if name in _RESERVED else name


def snake(camel):
    """`ConverterDataSource` -> `converter_data_source`."""
    s = re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", camel)
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s).lower()


