#!/usr/bin/env python3
"""Generate the header-only C++ wrapper for the whole public C API, in namespace `dewpp`.

The C API is what it has to be: opaque handles, out-parameters, caller-allocated `dew_error_t **`,
`(pointer, length)` string pairs, explicit destroy calls. That is right for an ABI and tedious to
write against, so this emits the C++ a caller actually wants -- RAII handles, `std::string_view` in,
`std::string` out, and errors returned by value -- from the same IR the Python bindings come from.
One description of the API, several wrappers, no hand-maintained duplicate.

    dewpp::converter_t conv = *dewpp::converter_t::create("out.dew", dew_open_file_semantics_truncate);
    conv.add_data_file(files);
    conv.wait_idle();

WHY std::expected AND NOT EXCEPTIONS. The project builds -fno-exceptions, so a failing constructor
cannot report by throwing. Every fallible call therefore returns `dewpp::result<T>` (an alias for
std::expected<T, dewpp::error>), and handle construction is a static factory rather than a
constructor. Note this means `.value()` must not be called on an error -- with -fno-exceptions it
cannot throw and will abort. Check `has_value()`, or dereference only after checking.

WHAT IS DELIBERATELY NOT WRAPPED. Enums, value structs and constants are ALIASED, not re-declared: a
parallel `enum class` would be a second source of truth that can drift from the C one, and the
conversion would buy nothing. Callback structs and function pointers are passed through as the C
types, because a std::function trampoline needs somewhere to live and the C API's single `void *`
user_ptr slot is already the caller's -- wrapping it would either leak or silently limit them to one
registration. That is a deliberate floor, not an oversight.

Usage:
    generate_cpp.py --api dew_api.json --output bindings/cpp/dew/dewpp.hpp [--check]
"""

